"""Driver-free portable checkpoint persistence boundary."""
from typing import Protocol, Any, Mapping, Sequence
from workbench_agent.domain.guards import ExecutionGuard
from workbench_agent.persistence.ports.uow import UnitOfWork

class CheckpointStorage(Protocol):
    async def put_with_guard(self,uow:UnitOfWork,guard:ExecutionGuard,payload:Mapping[str,Any]) -> Any: ...
    async def writes_with_guard(self,uow:UnitOfWork,guard:ExecutionGuard,namespace:str,checkpoint_id:str,writes:Sequence[Mapping[str,Any]]) -> None: ...
    async def rows(self,uow:UnitOfWork,guard:ExecutionGuard,namespace:str | None=None,checkpoint_id:str | None=None,before:str | None=None) -> Sequence[Mapping[str,Any]]: ...
    async def pending(self,uow:UnitOfWork,row:Mapping[str,Any]) -> Sequence[Mapping[str,Any]]: ...
    async def delete_terminal(self,uow:UnitOfWork,guard:ExecutionGuard) -> None: ...
