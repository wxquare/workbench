"""Caller-UoW admission/read port; no driver surface crosses this boundary."""
from typing import Protocol

class RunStore(Protocol):
    async def has_actions(self,uow,team_id,run_id) -> bool: ...
    async def one(self, uow, resource: str, **scope): ...
    async def insert(self, uow, resource: str, values: dict) -> None: ...
    async def replace_source(self, uow, source_event_id: str, values: dict) -> None: ...
    async def messages(self, uow, team_id: str, thread_id: str, *, limit=20, after=None): ...

    async def change(self,uow,resource,scope,values) -> int: ...
    async def generation(self,uow,run_id) -> int: ...
    async def current_scope(self,uow,team_id,run_id): ...
    async def waiting(self,uow,team_id,run_id): ...
    async def resume_pending(self,uow,team_id,run_id): ...
    async def checkpoint(self,uow,team_id,run_id): ...
    async def active_until(self,uow,team_id,run_id): ...
    async def all_evidence(self, uow, team_id, run_id): ...
    async def current_evidence(self,uow,team_id,run_id): ...
