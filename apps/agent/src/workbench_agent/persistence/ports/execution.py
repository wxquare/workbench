"""Driver-free Task 5 ports. All adapter calls share their caller's UoW."""
from typing import Protocol, Mapping, Any, Sequence
from workbench_agent.domain.guards import ExecutionGuard, ClaimedJob, WorkerCapabilities, RunReleaseStatus, JobQueueStatus
from workbench_agent.persistence.ports.uow import UnitOfWork

class ExecutionJobStore(Protocol):
    async def execution_attempt(self,uow:UnitOfWork,team_id:str,run_id:str) -> int: ...
    async def candidates(self,uow:UnitOfWork,limit:int=64,*,after:tuple | None=None,run_id:str | None=None) -> Sequence[Mapping[str,Any]]: ...
    async def has_priority_work(self,uow:UnitOfWork,capabilities:WorkerCapabilities) -> bool: ...
    async def claim(self,uow:UnitOfWork,capabilities:WorkerCapabilities,worker_id:str,candidates:Sequence[Mapping[str,Any]],*,projection:bool=False) -> tuple[ClaimedJob | None,Mapping[str,Any] | None]: ...
    async def continue_recovery(self,uow:UnitOfWork,guard:ExecutionGuard,checkpoint_id:str | None) -> None: ...
    async def lock_scope(self,uow:UnitOfWork,guard:ExecutionGuard) -> None: ...
    async def renew(self,uow:UnitOfWork,guard:ExecutionGuard) -> None: ...
    async def release(self,uow:UnitOfWork,guard:ExecutionGuard,*,status:RunReleaseStatus,job_status:JobQueueStatus | None=None,recovery_phase:str | None=None,retry_delay_ms:int=0,error_code:str | None=None) -> None: ...

class ExecutionLeaseGuard(Protocol):
    async def require(self,uow:UnitOfWork,guard:ExecutionGuard,allowed_statuses:frozenset[str]) -> None: ...

class ExecutionEventStore(Protocol):
    async def append_execution(self,uow:UnitOfWork,guard:ExecutionGuard,event_type:str,payload:Mapping[str,Any],*,message_id:str|None=None) -> int: ...
    async def append_control(self,uow,team_id,run_id,event_type,payload,*,message_id=None) -> int: ...

    async def rows(self,uow,team_id,run_id,after_seq,limit): ...
    async def expired_floor(self,uow,team_id,run_id,cutoff): ...
    async def prune(self,uow,team_id,run_id,cutoff): ...
    async def require_delivery(self,uow,guard): ...
    async def supersede_drafts(self,uow,guard,*,final_message_id=None): ...
