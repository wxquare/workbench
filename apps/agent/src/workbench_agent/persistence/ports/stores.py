"""Driver-free store contracts. Run services are connected in following tasks.

Every operation accepts the caller's UoW. CAS reports false (no mutation) or
raises STALE_EXECUTION for fencing; it must never silently overwrite state.
DTO mappings carry explicit scalar/codec fields from the canonical schema.
"""
from typing import Protocol, Mapping, Any, Sequence
from workbench_agent.persistence.ports.uow import UnitOfWork
from workbench_agent.domain.admin_jobs import AdminAuth, AdminJob, ClaimedAdminJob

Row = Mapping[str, Any]

class RunStore(Protocol):
    async def get(self,uow:UnitOfWork,team_id:str,run_id:str) -> Row | None: ...
    async def insert(self,uow:UnitOfWork,row:Row) -> None: ...
    async def cas(self,uow:UnitOfWork,team_id:str,run_id:str,revision:int,run_epoch:int,changes:Row) -> bool: ...

class JobStore(Protocol):
    async def insert(self,uow:UnitOfWork,row:Row) -> None: ...
    async def claim(self,uow:UnitOfWork,capabilities:set[str],worker_id:str) -> Row | None: ...

class ExecutionLeaseStore(Protocol):
    async def guard(self,uow:UnitOfWork,claim:Row) -> None: ...
    async def renew(self,uow:UnitOfWork,claim:Row) -> bool: ...

class CheckpointStore(Protocol):
    async def snapshot(self,uow:UnitOfWork,key:Row) -> Row | None: ...
    async def history(self,uow:UnitOfWork,key:Row,limit:int) -> Sequence[Row]: ...
    async def put(self,uow:UnitOfWork,guard:Row,snapshot:Row) -> None: ...
    async def put_writes(self,uow:UnitOfWork,guard:Row,writes:Sequence[Row]) -> None: ...
    async def delete(self,uow:UnitOfWork,team_id:str,run_id:str) -> None: ...

class RunEventStore(Protocol):
    async def append(self,uow:UnitOfWork,authorization:Row,event:Row) -> int: ...
    async def read(self,uow:UnitOfWork,team_id:str,run_id:str,after:int,limit:int) -> Sequence[Row]: ...

class ActionStore(Protocol):
    async def insert(self,uow:UnitOfWork,row:Row) -> None: ...
    async def cas(self,uow:UnitOfWork,team_id:str,action_id:str,revision:int,changes:Row) -> bool: ...

class OutboxStore(Protocol):
    async def insert(self,uow:UnitOfWork,row:Row) -> None: ...
    async def claim(self,uow:UnitOfWork,worker_id:str) -> Row | None: ...

class AdminJobStore(Protocol):
    async def submit(self,uow:UnitOfWork,auth:AdminAuth,kind:str,payload:str,request_hash:str,key:str) -> AdminJob: ...
    async def get(self,uow:UnitOfWork,auth:AdminAuth,job_id:str) -> AdminJob | None: ...
    async def claim(self,uow:UnitOfWork,capabilities:set[str],worker_id:str) -> ClaimedAdminJob | None: ...
    async def guard(self,uow:UnitOfWork,claim:ClaimedAdminJob) -> None: ...
    async def renew(self,uow:UnitOfWork,claim:ClaimedAdminJob) -> None: ...
    async def finish(self,uow:UnitOfWork,claim:ClaimedAdminJob,result_ref:str) -> None: ...
    async def fail(self,uow:UnitOfWork,claim:ClaimedAdminJob) -> None: ...
    async def upload_stage_references(self,uow:UnitOfWork) -> set[str]: ...
