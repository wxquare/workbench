"""Persistence contract for team knowledge entries."""

from typing import Protocol


class KnowledgeStore(Protocol):
    async def entry(self, uow, team_id: str, entry_id: str) -> dict | None: ...
    async def version(self, uow, team_id: str, entry_id: str, version: int) -> dict | None: ...
    async def entries(
        self, uow, team_id: str, *, limit: int, after: str | None, filters: dict
    ) -> list[dict]: ...
    async def versions(
        self, uow, team_id: str, entry_id: str, *, limit: int, after: int | None
    ) -> list[dict]: ...
    async def insert_entry(self, uow, row: dict) -> None: ...
    async def insert_version(self, uow, row: dict) -> None: ...
    async def cas_entry(
        self, uow, team_id: str, entry_id: str, expected_revision: int, changes: dict
    ) -> bool: ...
    async def next_version(self, uow, team_id: str, entry_id: str) -> int: ...
    async def replace_chunks(
        self, uow, team_id: str, entry_id: str, version: int | None, draft, chunks: tuple
    ) -> None: ...
    async def search_current(self, uow, scope, query: str, *, limit: int) -> list[dict]: ...
    async def indexed_chunks(self, uow, team_id: str) -> list[dict]: ...
    async def gap(self, uow, team_id: str, gap_id: str) -> dict | None: ...
    async def gap_by_digest(self, uow, team_id: str, digest: str) -> dict | None: ...
    async def gap_by_replay(self, uow, team_id: str, run_id: str) -> dict | None: ...
    async def replay_gap_id(self, uow, team_id: str, run_id: str) -> str | None: ...
    async def gaps(
        self, uow, team_id: str, *, limit: int, after: str | None, status: str | None
    ) -> list[dict]: ...
    async def insert_gap(self, uow, values: dict) -> None: ...
    async def cas_gap(
        self, uow, team_id: str, gap_id: str, expected_revision: int, changes: dict
    ) -> bool: ...
