from typing import AsyncContextManager, Protocol

class UnitOfWork(Protocol):
    """One connection and transaction, auto-commit on success, rollback on failure.

    Explicit commit/rollback ends the transaction; further access is rejected.
    Stores receive this same instance; never open a second UoW inside a guard.
    """
    def begin_read(self) -> AsyncContextManager["UnitOfWork"]: ...
    def begin_write(self) -> AsyncContextManager["UnitOfWork"]: ...
    async def commit(self) -> None: ...
    async def rollback(self) -> None: ...

class StorageClock(Protocol):
    async def now_ms(self, uow: UnitOfWork) -> int: ...
